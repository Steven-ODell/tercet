/** Up to eight `"🔥 fire"` choices: names starting with the query first, then any match. */
export function emojiChoices(query: string): readonly string[] {
  const wanted = query.toLowerCase().replace(/:$/, "");
  if (!wanted) return [];
  const score = ([, names]: readonly [string, string]) => {
    const words = names.split(" ");
    if (words.some((word) => word === wanted)) return 0;
    if (words.some((word) => word.startsWith(wanted))) return 1;
    return names.includes(wanted) ? 2 : 3;
  };
  return emoji
    .filter((entry) => score(entry) < 3)
    .toSorted((left, right) => score(left) - score(right))
    .slice(0, 8)
    .map(([character, names]) => `${character} ${names.split(" ")[0]}`);
}
